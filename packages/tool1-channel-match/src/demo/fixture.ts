/** 画像结构：把占比表转成内核输入。 */
export function toPortraitInput(profile: Profile, month: string): MatchPortraitInput {
  const dimensions: MatchPortraitInput['dimensions'] = {};
  for (const [dimension, labels] of Object.entries(profile)) {
    dimensions[dimension] = Object.fromEntries(
      Object.entries(labels).map(([label, share]) => [label, { share }]),
    );
  }
  const isWindow = month.includes('~');
  return {
    dimensions,
    month: isWindow ? month.split('~')[1]! : month,
    ...(isWindow ? { window: month } : {}),
  };
}
